# -*- coding: utf-8 -*-
"""ШАБЛОН Blueprint3D: минимальный объект с полным листом — копируется командой `bp3d new`.

Ящик инструментальный: корпус, крышка, ручка, замки, ножки, внутренний лоток.
Показывает всё, что нужно в любой спецификации: параметры сверху, детали с позициями и отделкой,
группы ext/int, зеркальные детали, виды, разрез, выносной вид, размеры, позиции, техтребования.
Мм; X — назад от передней точки, Y — влево, Z — вверх от земли.
"""
from bp3d.kit import rect, prism_yz, box, cyl, cut, mirror_y
from bp3d.model import Model

CODE = "XXX-000"
TITLE = "Ящик инструментальный"

# ---------------------------------------------------------------- параметры (все размеры — отсюда)
L, W, H_BODY = 200.0, 420.0, 142.0      # глубина по X, ширина по Y, высота корпуса
Z0 = 8.0                                # низ корпуса над землёй (высота ножек)
T = 2.0                                 # толщина стенки
GAP = 2.0                               # зазор корпус — крышка
H_LID = 26.0
Z_BODY = Z0 + H_BODY                    # верх корпуса
Z_LID = Z_BODY + GAP                    # низ крышки
Z_TOP = Z_LID + H_LID                   # верх крышки
Y_LATCH = 120.0                         # замки: расстояние от оси
HW = W / 2


def build_model():
    M = Model(code=CODE, title=TITLE)

    # корпус: наружный объём минус полость, открытую сверху
    body = cut(box(0, -HW, Z0, L, HW, Z_BODY, r=12),
               box(T, -HW + T, Z0 + T, L - T, HW - T, Z_BODY + 1, r=10))
    M.add("body", 1, "Корпус", "Сталь 0,8, окраска", body, finish="paint")

    # крышка: с напуском 3 мм, полость снизу. Тела перекрываются с запасом, а не касаются гранями
    lid = cut(box(-3, -HW - 3, Z_LID, L + 3, HW + 3, Z_TOP, r=14),
              box(T - 3, -HW - 3 + T, Z_LID - 1, L + 3 - T, HW + 3 - T, Z_TOP - T, r=12))
    M.add("lid", 2, "Крышка", "Сталь 0,8, окраска", lid, finish="paint")

    # ручка: контур вида спереди (y, z) со скруглениями, вытянут по X; низ утоплен в крышку на 2 мм
    handle = cut(prism_yz(rect(-72, Z_TOP - 2, 72, Z_TOP + 36, r=14), 92, 108),
                 prism_yz(rect(-60, Z_TOP - 12, 60, Z_TOP + 24, r=8), 90, 110))
    M.add("handle", 3, "Ручка", "Сталь, хром", handle, finish="chrome")

    # замок: левый строится, правый — зеркалом готовой детали (mirror_y), а не вторым построением
    latch = box(-6, Y_LATCH - 15, Z_BODY - 16, 1, Y_LATCH + 15, Z_LID + 12, r=2)
    M.add("latch_L", 4, "Замок-защёлка", "Сталь, цинк", latch, finish="metal")
    M.add("latch_R", 4, "Замок-защёлка", "Сталь, цинк", mirror_y(latch), finish="metal")

    # ножки: 4 шт., входят в дно на 1 мм
    for i, (x, y) in enumerate(((30, 180), (30, -180), (170, 180), (170, -180))):
        M.add(f"foot_{i}", 5, "Ножка", "Резина", cyl((x, y, 0), 12, 0, Z0 + 1, "z"), finish="rubber")

    # лоток: внутренняя деталь (group="int") — на видах штриховыми, в 3D в коллекции internal
    tray = cut(box(T + 2, -HW + T + 2, 96, L - T - 2, HW - T - 2, 138, r=8),
               box(T + 4, -HW + T + 4, 98, L - T - 4, HW - T - 4, 140, r=6))
    M.add("tray", 6, "Лоток", "Пластик ПП", tray, finish="plastic", group="int")
    return M


