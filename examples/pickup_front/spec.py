def ang_on(r, z):
    """Угол точки окружности колеса с высотой z (правая — задняя — половина)."""
    return math.degrees(math.asin((z - WC[1]) / r))


def bumper_x(y):
    """Передняя кромка бампера в плане."""
    return 60 * (abs(y) / 950) ** 3


# ------------------------------------------------------------------ капот
def hood_zt(x):   # верх по оси (купол), вид сбоку
    return smooth([(100, 1256), (150, 1270), (800, 1305), (1560, 1346)], x)


def hood_ze(x):   # кромка у крыла
    return lerp(1238, 1310, (x - 110) / 1450)


def hood_we(x):   # полуширина
    return lerp(800, 862, (x - 120) / 1440)


def hood_section(x):
    zt, ze, we = hood_zt(x), hood_ze(x), hood_we(x)
    zd = zt - 16
    crown = [(445 + (we - 445) * t, zd - (zd - ze) * t ** 1.7) for t in (0.25, 0.5, 0.75)]
    p = Path((-we, ze - 22))
    p.L((we, ze - 22), (we, ze))
    p.S(*reversed(crown), (445, zd))
    p.L((420, zt), (-420, zt), (-445, zd))
    p.S(*[(-y, z) for (y, z) in crown], (-we, ze))
    return p.close()


